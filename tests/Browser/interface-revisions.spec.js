const expect = baseExpect.configure({ timeout: 60_000 });
async function checkRecordIcons(page) {
    const controls = page.locator('[data-hoa-record-action]:visible');
    expect(await controls.count()).toBeGreaterThan(0);
    for (const control of await controls.all()) {
        await expect(control).toHaveAttribute('aria-label', /\S/);
        const box = await control.boundingBox();
        expect(box.width).toBeGreaterThanOrEqual(44);
        expect(box.height).toBeGreaterThanOrEqual(44);
        expect((await control.innerText()).trim()).toBe('');
        await expect(control.locator('svg').first()).toBeVisible();
    }
    const first = controls.first();
    await first.focus();
    await expect(first).toBeFocused();
}
